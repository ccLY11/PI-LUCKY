-- 4. 领取函数：已存在则返回原记录（duplicate = true），否则写入新记录
create or replace function public.pi_claim(
  p_name  text,
  p_no    text,
  p_code  text,
  p_pos   integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_name text;
  v_no   text;
  v_row  public.pi_claims;
begin
  v_name := btrim(coalesce(p_name, ''));
  v_no   := upper(btrim(coalesce(p_no, '')));

  if char_length(v_name) < 1 or char_length(v_name) > 20 then
    raise exception 'INVALID_NAME';
  end if;

  if v_no !~ '^[A-Z0-9_-]{4,24}$' then
    raise exception 'INVALID_NO';
  end if;

  if coalesce(p_code, '') !~ '^[0-9]{4}$' then
    raise exception 'INVALID_CODE';
  end if;

  if p_pos is null or p_pos < 1 or p_pos > 100000 then
    raise exception 'INVALID_POS';
  end if;

  -- 学号已领取：直接返回原有幸运码
  select * into v_row from public.pi_claims where student_no = v_no;
  if found then
    return jsonb_build_object(
      'ok', true,
      'duplicate', true,
      'name', v_row.name,
      'student_no', v_row.student_no,
      'code', v_row.code,
      'position', v_row.position,
      'created_at', v_row.created_at
    );
  end if;

  insert into public.pi_claims (student_no, name, code, position)
  values (v_no, v_name, p_code, p_pos)
  returning * into v_row;

  return jsonb_build_object(
    'ok', true,
    'duplicate', false,
    'name', v_row.name,
    'student_no', v_row.student_no,
    'code', v_row.code,
    'position', v_row.position,
    'created_at', v_row.created_at
  );

exception
  when unique_violation then
    -- 并发提交时的兜底：返回先写入的那条记录
    select * into v_row from public.pi_claims where student_no = v_no;
    return jsonb_build_object(
      'ok', true,
      'duplicate', true,
      'name', v_row.name,
      'student_no', v_row.student_no,
      'code', v_row.code,
      'position', v_row.position,
      'created_at', v_row.created_at
    );
end;
$$;

-- 5. 统计函数：密码正确时返回全部记录与总数
create or replace function public.pi_admin_list(p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_ok boolean;
begin
  select (password = coalesce(p_password, ''))
    into v_ok
    from public.pi_admin_config
   where id = 1;

  if not coalesce(v_ok, false) then
    raise exception 'AUTH_FAILED';
  end if;

  return jsonb_build_object(
    'total', (select count(*) from public.pi_claims),
    'rows', coalesce((
      select jsonb_agg(
               jsonb_build_object(
                 'name', name,
                 'student_no', student_no,
                 'code', code,
                 'position', position,
                 'created_at', created_at
               )
               order by created_at desc
             )
        from public.pi_claims
    ), '[]'::jsonb)
  );
end;
$$;

