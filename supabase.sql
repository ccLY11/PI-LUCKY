-- 1. 领取记录表：student_no 唯一，从数据库层面保证「每个学号只能领取一次」
create table if not exists public.pi_claims (
  id          bigint generated by default as identity primary key,
  student_no  text        not null unique,
  name        text        not null,
  code        text        not null,
  position    integer     not null,
  created_at  timestamptz not null default now()
);

comment on table public.pi_claims is 'Π 动嘉年华幸运码领取记录';

create index if not exists pi_claims_created_idx on public.pi_claims (created_at desc);
create index if not exists pi_claims_code_idx on public.pi_claims (code);

